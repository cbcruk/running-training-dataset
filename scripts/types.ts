#!/usr/bin/env node
/**
 * Generate TypeScript types from the JSON Schemas.
 *
 * The schemas are already the source of truth - `validate.mjs` enforces them and
 * nothing ships that violates one. Hand-writing interfaces alongside them would
 * create a second source that drifts silently, which is the same failure the
 * citation policy exists to prevent (docs/TODO.md #1a). So the types are derived,
 * checked in, and regenerated with `vp run types`.
 *
 * The output is committed so a fresh clone type-checks without running this first,
 * and CI re-runs it to prove the checked-in copy still matches the schemas.
 */
import { compile } from 'json-schema-to-typescript'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const schemaDir = resolve(root, 'data/schema')
const outDir = resolve(root, 'src/types')

const banner = `// GENERATED by scripts/types.ts from data/schema/*.json - do not edit.
// Run \`vp run types\` after changing a schema.
//
// Lint is off here on purpose: the shape of this file is the generator's business,
// and hand-fixing a warning would be undone by the next run.
/* eslint-disable */
`

// One module per schema. Every schema defines its own \`$defs/i18n\`, so compiling
// them into a single file would collide on the generated name; separate modules
// give each its own scope.
const ROOTS: Record<string, string> = {
  'workout.schema.json': 'Workout',
  'system.schema.json': 'System',
  'usage.schema.json': 'Usage',
  'anchor-model.schema.json': 'Anchor',
  'adaptation.schema.json': 'Adaptation',
}

const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith('.schema.json'))
  .sort()

const reexports: string[] = []
for (const f of files) {
  const schema = JSON.parse(readFileSync(resolve(schemaDir, f), 'utf8'))
  const name = ROOTS[f]
  if (!name) throw new Error(`no root type name mapped for ${f} - add it to ROOTS`)
  const ts = await compile(schema, name, {
    bannerComment: '',
    additionalProperties: false,
    style: { printWidth: 100 },
  })
  const stem = f.replace('.schema.json', '')
  writeFileSync(resolve(outDir, `${stem}.d.ts`), banner + '\n' + ts)
  reexports.push(`export type { ${name} } from "./${stem}.d.ts";`)
}

// Barrel: the five row types are what the views actually consume.
writeFileSync(resolve(outDir, 'index.d.ts'), `${banner}\n${reexports.join('\n')}\n`)

// Format with the repo's own formatter, so regenerating is idempotent: without
// this, `vp check --fix` reformats the output and the next run reports a diff.
execFileSync('./node_modules/.bin/vp', ['fmt', 'src/types'], { cwd: root, stdio: 'ignore' })

console.log(`src/types/ <- ${files.length} schemas (${files.map((f) => ROOTS[f]).join(', ')})`)
