#!/usr/bin/env node
/**
 * 소스 검증 작업지(docs/verification.md)를 생성한다.
 *
 * docs/TODO.md §1b는 설계상 사람의 일이다. 소스가 주장을 뒷받침한다고 기계가 단언하는
 * 것이 이 데이터셋이 피하려는 바로 그 실패이기 때문이다.
 *
 * 스크립트가 *할 수 있는* 일은 작업을 펼쳐놓는 것이다. 인용마다, 그것에 기대는 모든 행,
 * 그 행이 주장하는 정확한 문장, 그리고 그 문장이 내걸고 있는 등급. 그러면 검증자는 소스
 * 하나를 읽고 거기 달린 모든 주장을 한 번에 확인한다. grep으로 매핑을 다시 찾아내는
 * 대신에.
 *
 * src/types/처럼 생성되고 커밋된다. 행이 늘어도 조용히 낡을 수 없게. `vp run verify`로
 * 다시 만든다.
 */
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { load } from './dataset.ts'
import { assertions } from './evidence.ts'
import type { Assertion, AssertionKind } from './evidence.ts'

/* eslint-disable @typescript-eslint/no-explicit-any */
type Row = any

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const data = load(root)
const { workouts, systems, usage, anchors, adaptations, verified } = data
const rows = [...workouts, ...systems]

interface Use {
  row: string
  where: string
  tier: string
  assertion: string
  kind: AssertionKind
}
const byCite: Record<string, Use[]> = {}

const pick = (v: Row): string => (typeof v === 'string' ? v : '')

/**
 * 가장 가까운 반증 가능한 문장에, 그것이 어떤 종류인지를 표시한다. test의 것은 생리학적
 * 발견이 아니고, 관찰 불가능한 test의 것은 왜 아무것도 그것을 해결하지 못하는지에 대한
 * 진술이다. 검증자는 소스를 열기 전에 자기가 무엇을 읽고 있는지 알아야 한다.
 */
const label = (a: Assertion): string => {
  const text = pick(a.proposition)
  if (!text) return ''
  if (a.kind === 'test') return `(test) ${text}`
  if (a.kind === 'unobservable-test') return `(관찰 불가능한 test) ${text}`
  return text
}

for (const row of rows)
  for (const a of assertions(row))
    for (const c of a.evidence.cite ?? [])
      (byCite[c] ??= []).push({
        row: row.id,
        where: a.path || '(row itself)',
        tier: a.evidence.tier,
        assertion: label(a),
        kind: a.kind,
      })

/**
 * 읽은 기록. `data/verified.json`은 생성되지 않으므로, 이 파일이 매번 새로 쓰여도
 * 체크는 살아남는다 — 체크박스가 소스가 아니라 원장의 그림자이기 때문이다.
 */
const readings = new Map<string, Row>()
for (const v of verified) readings.set(`${v.row} ${v.path} ${v.cite}`, v)

const cites = Object.keys(byCite).sort()
const tierCount: Record<string, number> = {}
for (const uses of Object.values(byCite))
  for (const u of uses) tierCount[u.tier] = (tierCount[u.tier] ?? 0) + 1

const lines: string[] = [
  '<!-- GENERATED by scripts/verify.ts - do not edit. Run `vp run verify`. -->',
  '',
  '# 소스 검증 작업지',
  '',
  '[`TODO.md` §1b](TODO.md#1b-소스가-뒷받침하는지-확인)의 체크리스트다.',
  '데이터에서 생성되므로, 여기가 서술하는 행과 어긋날 수 없다.',
  '',
  '**여기 있는 것은 아무것도 검증되지 않았다.** `validate.ts`는 생성기가',
  '`status: verified`를 쓰는 것을 금지한다. 그 전환은 행 단위로, 소스를 읽은 뒤에',
  '사람이 하는 행위다. 이 파일은 무엇을 읽고 무엇과 대조할지만 말한다.',
  '',
  `**소스 ${cites.length}개**가 **주장 ${Object.values(tierCount).reduce((a, b) => a + b, 0)}개**를 떠받친다 ` +
    `(${Object.entries(tierCount)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([t, n]) => `${t} ${n}`)
      .join(', ')}).`,
  '',
  '쓰는 법: 소스 하나를 잡아 한 번 읽고, 아래에 달린 행들을 훑는다. 각 행에서 묻는 것은',
  '*이게 참인가*가 아니라 **이 소스가 그렇게 말하는가**다. 아니라면 그 행은 `tradition`으로',
  '내려가고, 그건 인용을 제거한다는 뜻이다 — `tradition` + `cite`는 검증 오류이기 때문이다.',
  '',
  '---',
  '',
]

for (const cite of cites) {
  const uses = byCite[cite]
  lines.push(`## ${cite}`, '')
  lines.push(`주장 ${uses.length}개를 떠받친다:`, '')
  for (const u of uses) {
    const r = readings.get(`${u.row} ${u.where === '(row itself)' ? '' : u.where} ${cite}`)
    const head = `- [${r ? (r.supports ? 'x' : '-') : ' '}] \`${u.row}\` · \`${u.where}\` · **${u.tier}**`
    lines.push(
      u.assertion
        ? `${head} — "${u.assertion}"`
        : `${head} — _(반증 가능한 문장이 붙어 있지 않음)_`,
    )
    if (r) lines.push(`      _${r.supports ? '확인' : '기각'} · ${r.by} · ${r.on}_ — ${r.note}`)
  }
  lines.push('')
}

/**
 * 훈련법 행과 distribution에만 인용된 소스는 반증 가능한 문장에 한 번도 붙지 않는다.
 * 대개 정경 텍스트가 효능 근거인 양 쓰이고 있는 경우이고, 등급 체계가 잡으려고 존재하는
 * 범주 오류다.
 */
const methodOnly = cites.filter((c) => byCite[c].every((u) => !u.assertion))
/**
 * `consensus`는 등급표에서 가장 높은 바다. 행은 가장 적고 주장은 가장 크므로 먼저
 * 확인한다.
 */
const consensus = cites.filter((c) => byCite[c].some((u) => u.tier === 'consensus'))
/** 행 스스로 관찰 불가능하다고 말하면서 `tradition`을 넘는 등급을 단 test. */
const unobservable: string[] = []
for (const c of cites)
  for (const u of byCite[c])
    if (u.kind === 'unobservable-test' && u.tier !== 'tradition')
      unobservable.push(`\`${u.row}\` (${u.tier}) — ${c}`)

/**
 * `source` 항목은 근거가 아니라 출처이므로 위의 모든 것에서 의도적으로 빠져 있다 —
 * 대조할 주장이 없다. 그래도 나열해두면 그것이 조용한 누락이 아니라 진술된 선택으로 남는다.
 */
const sourced = rows.filter((r: Row) => r.source?.length)
lines.push('---', '', '## 범위 밖: 출처', '')
lines.push(
  '이 참조들은 `cite`가 아니라 `source`다. 훈련법이 무엇을 *처방하는지*를 기록할 뿐이고,',
  '그것이 작동하는지는 별개의 질문이다. 근거로 제시된 것이 없으므로 주장과 대조할 것도',
  '없다. `validate.ts`가 둘을 갈라놓는다 — 한 행에서 같은 참조가 둘 다일 수는 없다.',
  '',
)
if (sourced.length)
  for (const s of sourced) for (const src of s.source) lines.push(`- \`${s.id}\` — ${src}`)
else lines.push('- _(없음)_')
lines.push('')

// 이 작업지가 열었던 세 질문은 해결됐고, 각각은 누군가 기억하기를 바라는 문단이 아니라
// validate.ts의 규칙이 됐다. 살아 있는 가드로 남겨둔다. 여기서 회귀가 생기면 이 파일에
// 닿기 전에 빌드가 실패하므로, 아래 목록이 비어 있다는 것은 검사가 건너뛰어진 것이
// 아니라 통과했다는 뜻이다.
lines.push('---', '', '## 트리아지: 해결됐고 이제 기계가 강제한다', '')
lines.push(
  '소스를 열지 않고 답할 수 있던 질문 셋이다. 각각은 이제 `validate.ts` 규칙이므로,',
  '아래 목록이 채워지려면 그 전에 빌드가 실패한다 — 작업 목록이 아니라 살아 있는',
  '검사 결과로 찍힌다.',
  '',
)
const guard = (heading: string, why: string, items: string[]) => {
  lines.push(`### ${heading}`, '', why, '')
  if (items.length) for (const i of items) lines.push(`- [ ] ${i}`)
  else lines.push('- _(없음 — 규칙이 지켜지고 있다)_')
  lines.push('')
}
guard(
  '1. 반증 가능한 문장에 한 번도 붙지 않은 소스',
  '`claim.proposition`을 뒷받침하지 않는 소스는 자기가 무엇의 근거인지 진술된 것이 없다. ' +
    '리뷰에는 대조할 명제를 주었고, 정경 텍스트는 `tradition`으로 내려가 `source`로 옮겼다.',
  methodOnly.map((c) => `${c}\n      _행: ${byCite[c].map((u) => `\`${u.row}\``).join(', ')}_`),
)
guard(
  '2. `consensus` 행',
  '`consensus`는 분야가 동의한다고 주장하는데, 어떤 단일 소스도 그것을 진술하지 않고 ' +
    '생성기가 서지에서 읽어낼 수도 없다. 이제 `status: verified` — 사람의 읽기 — 를 ' +
    '요구하며, `test` 슬롯에는 아예 닫혀 있다.',
  consensus.flatMap((c) =>
    byCite[c].filter((u) => u.tier === 'consensus').map((u) => `\`${u.row}\`.${u.where} — ${c}`),
  ),
)
guard(
  '3. `tradition`을 넘는 관찰 불가능한 test',
  '시드 데이터에서 인용을 가진 test 여덟 개 전부가 자기 claim의 참조를 글자 그대로 ' +
    '재사용했다. 이제 test의 근거는 claim의 것과 서로소여야 하며, test가 인용해도 되는 것은 ' +
    '*측정*에 관한 소스다.',
  unobservable,
)

writeFileSync(resolve(root, 'docs/verification.md'), lines.join('\n'))

/**
 * 산문이 인용하고 싶어 하는 모든 수치를, 손으로 적는 대신 데이터에서 유도한다. 손으로 쓴
 * 총계는 이미 한 번 낡았다 — README가 관찰 불가능한 test를 열셋일 때 둘이라고 적고
 * 있었다 — 그리고 등급이 바뀔 때마다 사람이 다시 세야 하는 산문은 또 낡는다.
 */
const tally = (list: Row[], of: (r: Row) => string | undefined): Record<string, number> => {
  const out: Record<string, number> = {}
  for (const r of list) {
    const k = of(r)
    if (k) out[k] = (out[k] ?? 0) + 1
  }
  return out
}
const tiersOf = (list: Row[]): Record<string, number> =>
  tally(
    list.flatMap((r: Row) => assertions(r)),
    (a) => a.evidence.tier,
  )

const order = ['consensus', 'plausible', 'tradition']
const tiers = tiersOf(rows)
const row = (label: string, counts: Record<string, number>, keys: string[]): string =>
  `| ${label} | ${keys.map((k) => counts[k] ?? 0).join(' | ')} | ${keys.reduce((a, k) => a + (counts[k] ?? 0), 0)} |`

const provKeys = ['recorded', 'unrecorded', 'uncitable']
// 용량 질문은 `tradition` 근거에만 달리고 워크아웃에만 있다. 여기서 세는 이유는 README가
// 이 구분을 산문으로 설명하면서 개수를 손으로 적고 있었기 때문이다 — 이 파일이 존재하는
// 이유가 바로 그 손으로 쓴 총계가 낡는 것이다.
const doseKeys = ['open', 'unaskable']
const doses: Record<string, number> = {}
const unaskableRows: string[] = []
for (const w of workouts as Row[]) {
  const walk = (node: Row) => {
    if (Array.isArray(node)) return node.forEach(walk)
    if (!node || typeof node !== 'object') return
    if (node.tier === 'tradition' && node.dose_question) {
      doses[node.dose_question] = (doses[node.dose_question] ?? 0) + 1
      if (node.dose_question === 'unaskable' && !unaskableRows.includes(w.id))
        unaskableRows.push(w.id)
    }
    for (const v of Object.values(node)) walk(v)
  }
  walk(w)
}

const counts: string[] = [
  '<!-- GENERATED by scripts/verify.ts - do not edit. Run `vp run verify`. -->',
  '',
  '# 카운트',
  '',
  '`data/*.json`에서 유도된다. 다른 곳의 산문은 숫자를 인용하는 대신 여기를 가리키므로,',
  '등급이 바뀌어도 낡은 총계가 뒤에 남지 않는다.',
  '',
  '## 행 수',
  '',
  '| 훈련법 | 워크아웃 | 용례 | 앵커 | 적응 |',
  `| --- | --- | --- | --- | --- |`,
  `| ${systems.length} | ${workouts.length} | ${usage.length} | ${anchors.length} | ${adaptations.length} |`,
  '',
  '## 근거 등급',
  '',
  '근거 객체 단위로 센다. 어디에 달려 있든 — 행 자신의 `evidence`, `claim`, `test`,',
  '`distribution`, `volume_cap`.',
  '',
  `| | ${order.join(' | ')} | 합계 |`,
  `| --- | ${order.map(() => '---').join(' | ')} | --- |`,
  row('전체', tiers, order),
  row('워크아웃', tiersOf(workouts), order),
  row('훈련법', tiersOf(systems), order),
  '',
  '`consensus`는 `status: verified`를 요구하고 검증된 행은 아직 없으므로, 비어 있는 최상위',
  '등급은 구멍이 아니라 바가 지켜지고 있다는 뜻이다. `tradition`이 지배하는 것이 러닝 지식의',
  '정직한 형태이며, 그 비율을 억지로 뒤집으면 프로젝트가 죽는다.',
  '',
  '## 출처 상태',
  '',
  '`source`의 상태 — 규정 텍스트가 기록되어 있는지, 존재하지만 여기 기록되지 않았는지,',
  '아예 존재할 수 없는지.',
  '',
  `| | ${provKeys.join(' | ')} | 합계 |`,
  `| --- | ${provKeys.map(() => '---').join(' | ')} | --- |`,
  row(
    '훈련법',
    tally(systems, (s) => s.provenance),
    provKeys,
  ),
  row(
    '워크아웃',
    tally(workouts, (w) => w.provenance),
    provKeys,
  ),
  '',
  '## 용량 질문',
  '',
  '`tradition` 근거가 어떤 종류의 모름인지. `open`은 통제 연구를 돌릴 수 있는데 아무도',
  '돌리지 않은 것이고, `unaskable`은 구간이 예시일 뿐이라 "얼마나"에 가리킬 대상이 없는',
  '것이다. 앞의 것만 연구가 메울 수 있는 공백이다. 워크아웃 전용이다 — 훈련법은',
  '프로토콜이 아니라 내기이고, 용량 질문은 프로토콜에 묻는다.',
  '',
  `| | ${doseKeys.join(' | ')} | 합계 |`,
  `| --- | ${doseKeys.map(() => '---').join(' | ')} | --- |`,
  row('tradition 근거 객체', doses, doseKeys),
  '',
  `\`unaskable\`인 워크아웃: ${unaskableRows.length ? unaskableRows.map((id: string) => `\`${id}\``).join(', ') : '_(없음)_'}.`,
  '',
  '## 반증 가능성',
  '',
  '| 관찰 가능한 test | 관찰 불가능한 test |',
  `| --- | --- |`,
  `| ${workouts.filter((w: Row) => w.test.detectable).length} | ${workouts.filter((w: Row) => !w.test.detectable).length} |`,
  '',
  '관찰 불가능한 test는 어떤 현장 관측도 이것을 해결하지 못하는 이유를 `mechanism`에 싣고,',
  '`what`·`when_weeks`·`confounds`·`if_absent`를 가질 수 없다 — 관찰 불가능한 영가설은',
  '해석될 수 없다.',
  '',
]
writeFileSync(resolve(root, 'docs/counts.md'), counts.join('\n'))

execFileSync('./node_modules/.bin/vp', ['fmt', 'docs/verification.md', 'docs/counts.md'], {
  cwd: root,
  stdio: 'ignore',
})
console.log(`docs/verification.md <- ${cites.length} sources`)
console.log(`docs/counts.md <- tiers ${JSON.stringify(tiers)}`)
